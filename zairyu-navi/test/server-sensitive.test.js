// 敏感号码过滤的规则表。README“敏感号码过滤”一节写的每一条，这里都有对应的例子。
const test = require('node:test');
const assert = require('node:assert/strict');
const { findSensitive, assertNoSensitive, isDate } = require('../src/validate');

test('过滤：个人编号（12位，含分隔符、全角、关键词后的任意分组）', () => {
  for (const s of ['123456789012', '编号123456789012。', '1234 5678 9012', '1234-5678-9012', '1234.5678.9012', '1234・5678・9012', '1234　5678　9012',
    '１２３４５６７８９０１２', '１２３４－５６７８－９０１２', '1234 - 5678 - 9012', '个人编号：123 456 789 012', 'マイナンバーは 12-3456-7890-12 です', 'My Number 123456 789012', '個人番号 1 2 3 4 5 6 7 8 9 0 1 2']) {
    assert.equal(findSensitive(s), 'mynumber', s);
  }
});

test('过滤：护照号', () => {
  for (const s of ['EA1234567', 'E12345678', 'G12345678', 'tk1234567', '护照号EA1234567', 'ＥＡ１２３４５６７', '护照号码是 12345678', 'passport no. 1234567', '旅券番号：TR 1234567', 'パスポート番号 MZ1234567']) {
    assert.equal(findSensitive(s), 'passport', s);
  }
});

test('过滤：银行账号和卡号', () => {
  for (const s of ['6222021234567890123', '4111111111111111', '4111 1111 1111 1111', '4111-1111-1111-1111', '４１１１　１１１１　１１１１　１１１１', '账号 1234567', '银行账号：123-1234567', '口座番号 1234567', '口座は 12345-12345678 です', '卡号是1234567890', '我的账户 7654321', 'bank account 12345678', 'Bank account no. 1234567', 'account number: 0012345']) {
    assert.equal(findSensitive(s), 'bank', s);
  }
});

test('过滤：日期、电话、金额、邮编、在留卡号等不拦', () => {
  for (const s of ['', '想咨询永驻申请，目前在留8年、就劳6年。', '2026-11-30', '2026-11-30 2027-01-15', '2026年11月30日到2027年1月15日', '2026/11/30～2027/01/15', '20261130', '20261130 20270115',
    '090-1234-5678', '09012345678', '06-1234-5678', '+81 90 1234 5678', '+86 138 1234 5678', '13812345678', '电话 090-1234-5678 2026年入境', '0120-123-456',
    '1,200,000日元', '1200000 日元', '年收 12000000 日元', '5,500日元（约260元）', '123,456,789,012 日元', '〒530-0001', '法人番号 1234567890123', '在留卡号 AB12345678CD',
    '账户余额 1200000 日元', '口座里有 3000000 円', '账号是 2026-11-30 开的', '开设口座需要在留卡', '护照号码页复印件', '护照 2030-05-01 到期', 'passport number is on page 2',
    '第00000000号', 'N1', 'A4 纸 2 张', '任务 4-10', '14天内', '10:30-11:30', '2026.11.30', '我的微信 abc_12345']) {
    assert.equal(findSensitive(s), null, s);
  }
  assert.equal(findSensitive(null), null); assert.equal(findSensitive(123456789012), null, '只检查文字');
});

test('过滤：报错信息说明是哪段文字、哪一类号码', () => {
  assert.throws(() => assertNoSensitive('1234 5678 9012', '摘要'), (e) => e.status === 422 && /摘要里疑似含有个人编号/.test(e.message));
  assert.throws(() => assertNoSensitive('EA1234567', '消息'), (e) => e.status === 422 && /消息里疑似含有护照号/.test(e.message));
  assert.throws(() => assertNoSensitive('账号 1234567', '回复'), (e) => e.status === 422 && /回复里疑似含有银行账号或卡号/.test(e.message));
  assert.doesNotThrow(() => assertNoSensitive('电话 090-1234-5678', '摘要'));
  assert.doesNotThrow(() => assertNoSensitive(undefined, '备注'));
});

test('日期：isDate 只认日历上存在的 YYYY-MM-DD', () => {
  for (const d of ['2026-01-01', '2028-02-29', '2026-12-31', '2000-02-29']) assert.equal(isDate(d), true, d);
  for (const d of ['2026-02-30', '2026-02-29', '2025-02-31', '2026-04-31', '2026-13-01', '2026-00-01', '2026-01-00', '2026-1-1', '2026/01/01', '', null, undefined, ['2026-01-01'], 20260101, '2026-01-01T00:00:00']) assert.equal(isDate(d), false, String(d));
});

test('过滤：12位数字不论怎么分组、用什么分隔符都拦（没有关键词）', () => {
  for (const s of ['想咨询 123456 789012 的事', '想咨询 123456-789012 的事', '想咨询 123 456 789 012 的事', '12345 6789012', '12345678 9012', '12-3456-7890-12',
    '1234/5678/9012', '1234,5678,9012', '1234、5678、9012', '1234\n5678\n9012', '1234|5678|9012', '1234:5678:9012', '1234~5678~9012', '1234​5678​9012', '12‍34567890﻿12',
    '金额 1234.5678.9012', '住址 1-2-3, 1234 5678 9012', 'abc 12 123456789012']) {
    assert.equal(findSensitive(s), 'mynumber', JSON.stringify(s));
  }
  for (const s of ['my number: 1234/5678/9012', '个人编号是 1234、5678、9012', '个人编号\n1234\n5678\n9012', 'マイナンバー 123,456,789,012', '个人编号 202611271530', '个人编号 2023 2024 2025']) {
    assert.equal(findSensitive(s), 'mynumber', '关键词后面不论怎么分组：' + JSON.stringify(s));
  }
});

test('过滤：几个年份、年月日时分、带 + 的电话、带单位的价格不当成个人编号或卡号', () => {
  for (const s of ['需要 2023 2024 2025 三年的纳税证明', '2023-2024-2025年度', '课税证明 2023・2024・2025', '2019 2021 2026', '2023、2024、2025 三个年度', '2022 2023 2024 2025 四年的课税证明',
    '请准备 2023 2024 2025 三个年度的课税证明书和纳税证明书', '2023 2024 2025 年都住这里',
    '订单 2026 1127 1530', '预约 202611271530', '2026/11/30 10:30', '2026-11-30 10:30 来窗口', '2026-11-30 5500日元',
    '+8190-1234-5678', '+819012345678', '+81 90-1234-5678', '090-1234-5678 03-1234-5678',
    '套餐 2980/3980/4980 日元', '月收 200000~250000日元', '2980、3980、4980、5980 日元',
    '服务商 3f2a1b4c-1234-5678-9012-123456789012']) {
    assert.equal(findSensitive(s), null, JSON.stringify(s));
  }
});

test('过滤：卡号、IBAN、日本的支店加账号、字母和数字隔开写的护照号', () => {
  for (const s of ['4111/1111/1111/1111', '4111 1111\n1111 1111', '4111,1111,1111,1111', 'IBAN GB29NWBK60161331926819', 'iban: GB29 NWBK 6016 1331 9268 19', '支店 123 普通 7654321', '店番123 当座 1234567']) assert.equal(findSensitive(s), 'bank', JSON.stringify(s));
  for (const s of ['passport E 12345678', '护照 EA 1234567', '旅券 G 12345678']) assert.equal(findSensitive(s), 'passport', s);
  for (const s of ['支店在梅田，普通的窗口 2026年办', 'IBAN 是什么', 'passport page 2 12345']) assert.equal(findSensitive(s), null, s);
});

test('过滤：已知会误拦的写法（README“已知的局限”里写明的，改规则时这里跟着改）', () => {
  // 和护照号同形的其他编号：1个字母+8位数字、2个字母+7位数字
  for (const s of ['学号 A12345678', '签证申请号 E12345678', '航班 NH1234567']) assert.equal(findSensitive(s), 'passport', s);
  // 三个四位数连写、两个六位数的范围，后面没有金额单位
  for (const s of ['套餐 2980/3980/4980', '月收 200000-250000']) assert.equal(findSensitive(s), 'mynumber', s);
});
